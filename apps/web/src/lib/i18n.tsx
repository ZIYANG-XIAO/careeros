export type MessageKey = keyof (typeof messages)["en"];

type I18nValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey) => string;
};

const defaultValue: I18nValue = {
  locale: "en",
  setLocale: () => undefined,
  t: (key) => messages.en[key],
};

const I18nContext = createContext<I18nValue>(defaultValue);
const STORAGE_KEY = "careeros.locale";

export function LocaleProvider({
  children,
  initialLocale = "en",
}: {
  children: ReactNode;
  initialLocale?: Locale;
}) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale);

  function setLocale(next: Locale) {
    setLocaleState(next);
    window.localStorage.setItem(STORAGE_KEY, next);
    document.cookie = `careeros_locale=${next}; Path=/; Max-Age=31536000; SameSite=Lax`;
    document.documentElement.lang = next;
  }

  const value = useMemo<I18nValue>(
    () => ({ locale, setLocale, t: (key) => messages[locale][key] }),
    [locale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

export function intlLocale(locale: Locale): string {
  return locale === "zh-CN" ? "zh-CN" : "en-US";
}

export function formatLocaleDate(
  locale: Locale,
  value: string | null | undefined,
  options: Intl.DateTimeFormatOptions = { dateStyle: "medium" },
): string | null {
  if (!value) return null;
  return new Intl.DateTimeFormat(intlLocale(locale), options).format(
    new Date(value),
  );
}

const APPLICATION_STATUS_KEYS = {
  PREPARING: "applications.status.PREPARING",
  APPLIED: "applications.status.APPLIED",
  ASSESSMENT: "applications.status.ASSESSMENT",
  INTERVIEW: "applications.status.INTERVIEW",
  FINAL: "applications.status.FINAL",
  REJECTED: "applications.status.REJECTED",
  OFFER: "applications.status.OFFER",
  WITHDRAWN: "applications.status.WITHDRAWN",
} as const satisfies Record<string, MessageKey>;

export type ApplicationStatusKey = keyof typeof APPLICATION_STATUS_KEYS;

export function applicationStatusLabel(
  status: ApplicationStatusKey,
  t: (key: MessageKey) => string,
): string {
  return t(APPLICATION_STATUS_KEYS[status]);
}

export function formatResumeVersionLabel(
  resumeName: string,
  versionNumber: number,
  t: (key: MessageKey) => string,
): string {
  return `${resumeName} · ${t("common.version")} ${versionNumber}`;
}

export function formatCareerDateRange(
  start: string | null,
  end: string | null,
  t: (key: MessageKey) => string,
  options?: { isCurrent?: boolean },
): string | null {
  const unknown = t("common.unknownDate");
  if (options?.isCurrent !== undefined) {
    if (!start && !end && !options.isCurrent) return null;
    const endLabel = options.isCurrent ? t("common.present") : (end ?? unknown);
    return `${start ?? unknown} — ${endLabel}`;
  }
  if (!start && !end) return null;
  return `${start ?? unknown} — ${end ?? t("common.present")}`;
}

export function getMessageKeys(locale: Locale): MessageKey[] {
  return Object.keys(messages[locale]) as MessageKey[];
}
